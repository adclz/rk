//! rk-bindgen: the ST declarations of the interfaces a WIT world imports,
//! as wit-bindgen writes Rust for them. Each test generates a small WIT
//! package's declarations, shows them, and checks that rk takes them; the
//! last ones generate the interfaces `Std` reaches WASI through, from the
//! WASI rk carries, and build them into a component, which checks each
//! import's name against WASI's WIT.

use db::RootDatabase;
use insta::assert_snapshot;
use rstest::rstest;

use crate::tests::utils::{lower_workspace, test_diagnostics, with_db};

/// The files rk-bindgen writes for the world in `wit`, a package of its own
/// beside the WASI rk carries.
fn generated(wit: &str) -> Vec<rk_bindgen::File> {
    let (resolve, world) = rk_bindgen::resolve(wit).expect("the WIT resolves");
    rk_bindgen::generate(&resolve, world).expect("it generates")
}

/// Each file after a line with its name.
fn shown(files: &[rk_bindgen::File]) -> String {
    files
        .iter()
        .map(|file| format!("// {}\n{}", file.name, file.text))
        .collect::<Vec<_>>()
        .join("\n")
}

/// The diagnostics rk reports on `files`: none when it takes them, and
/// then the workspace also lowers and validates.
fn reported(db: &mut RootDatabase, files: &[rk_bindgen::File]) -> String {
    let texts: Vec<&str> = files.iter().map(|file| file.text.as_str()).collect();
    test_diagnostics(db, &texts)
}

/// A scalar is a variable of its ST type, an alias a TYPE, an enum a typed
/// enum whose base holds its cases as the canonical ABI does, and a name
/// that is a keyword of ST takes a `_` after it.
#[rstest]
fn scalars_aliases_and_enums(mut with_db: RootDatabase) {
    let files = generated(
        r#"
        package wasi:example@0.3.0;

        interface clock {
            /// A count of ticks.
            type ticks = u64;
            enum unit { second, milli-second }
            now: func() -> ticks;
            scale: func(value: s32, by: unit) -> f64;
            reset: func();
        }

        interface exit {
            exit: func(code: u8, flag: bool, small: s8, wide: u16, half: s16, ratio: f32);
        }

        world example {
            import clock;
            import exit;
        }
        "#,
    );
    assert_snapshot!(shown(&files), @r"
    // wasi-example-clock.st
    /* Generated by rk-bindgen from the WIT of wasi:example@0.3.0. Do not edit:
       `cargo run -p rk-bindgen` writes it again. */
    NAMESPACE INTERNAL Wasi
    	NAMESPACE Example
    		NAMESPACE Clock
    			/* A count of ticks. */
    			TYPE TICKS : ULINT; END_TYPE

    			TYPE UNIT : USINT (
    				SECOND := 0,
    				MILLI_SECOND := 1
    			); END_TYPE

    			{extern 'wasi:example/clock@0.3.0' 'now'}
    			FUNCTION NOW : TICKS
    			END_FUNCTION

    			{extern 'wasi:example/clock@0.3.0' 'scale'}
    			FUNCTION SCALE : LREAL
    			VAR_INPUT
    				value : DINT;
    				by_ : UNIT;
    			END_VAR
    			END_FUNCTION

    			{extern 'wasi:example/clock@0.3.0' 'reset'}
    			FUNCTION RESET
    			END_FUNCTION
    		END_NAMESPACE
    	END_NAMESPACE
    END_NAMESPACE

    // wasi-example-exit.st
    /* Generated by rk-bindgen from the WIT of wasi:example@0.3.0. Do not edit:
       `cargo run -p rk-bindgen` writes it again. */
    NAMESPACE INTERNAL Wasi
    	NAMESPACE Example
    		NAMESPACE Exit_
    			{extern 'wasi:example/exit@0.3.0' 'exit'}
    			FUNCTION EXIT_
    			VAR_INPUT
    				code : USINT;
    				flag : BOOL;
    				small : SINT;
    				wide : UINT;
    				half : INT;
    				ratio : REAL;
    			END_VAR
    			END_FUNCTION
    		END_NAMESPACE
    	END_NAMESPACE
    END_NAMESPACE
    ");
    assert_snapshot!(reported(&mut with_db, &files), @"");
}

/// A record or a tuple passed in is one input per field, as the canonical
